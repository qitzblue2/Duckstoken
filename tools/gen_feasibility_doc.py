#!/usr/bin/env python3
"""Regenerate docs/GPT_OSS_120B.md from the planner so the numbers in the document are the numbers the app shows.

    python tools/gen_feasibility_doc.py            # writes docs/GPT_OSS_120B.md
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from duckstoken.vgpu import gptoss, hwmodel  # noqa: E402


def v(x, nd=1):
    return "n/a" if x is None or x.get("value") is None else f"{x['value']:.{nd}f}"


def rng(x):
    val = (x or {}).get("value")
    return "not loadable" if not val else f"{val[0]}–{val[1]}"


def section(title: str, preset: str, **kw) -> list[str]:
    hw = hwmodel.preset_hardware(preset, **kw)
    out = [f"### {title}", ""]
    for model in ("gpt-oss-120b", "gpt-oss-20b"):
        r = gptoss.feasibility_report(hw, model, 4096)
        out += [f"**{model}** — verdict **{r['verdict']}**" + ("" if r["verdict"] == "not_realistic" else f", ≈ {rng(r['tokens_per_s'])} tokens/s *(estimate)*"), "", r["explanation"], ""]
    return out


def main() -> None:
    hw = hwmodel.preset_hardware("duck-user")
    r = gptoss.feasibility_report(hw, "gpt-oss-120b", 4096)
    rq = r["requirements"]
    s120, s20 = gptoss.SPECS["gpt-oss-120b"], gptoss.SPECS["gpt-oss-20b"]
    lines = [
        "# GPT-OSS 120B feasibility report",
        "",
        "> Generated by `tools/gen_feasibility_doc.py` from the same planner the app uses (**Virtual GPU → GPT-OSS 120B**).",
        "> Every number below is an **estimate** from published model facts and a memory-bandwidth model. Nothing here was",
        "> measured on a real gpt-oss-120b, because that needs a 63 GB download and ≥ 48 GB of RAM that the development sandbox",
        "> does not have. Run the app on your PC to replace estimates with measurements.",
        "",
        "## The model (official facts)",
        "",
        "| | gpt-oss-120b | gpt-oss-20b |",
        "|---|---|---|",
        f"| Parameters (total / active per token) | 117 B / 5.1 B | 21 B / 3.6 B |",
        f"| Layers | {s120['layers']} | {s20['layers']} |",
        f"| Experts (used per token) | {s120['experts']} ({s120['experts_used']}) | {s20['experts']} ({s20['experts_used']}) |",
        "| Attention | 64 heads, 8 KV heads, head dim 64, alternating sliding-window (128) / full | same |",
        "| Context | up to 131 072 tokens | same |",
        "| Weights format | MXFP4 for the MoE weights (≈ 4.25 bits/weight) | same |",
        "| Official GGUF (`ggml-org`) | `gpt-oss-120b-MXFP4.gguf`, 63.4 GB (≈ 59.0 GiB) | `gpt-oss-20b-MXFP4.gguf`, ≈ 12.1 GB |",
        "",
        "Sources: the model cards and `config.json` files at <https://huggingface.co/openai/gpt-oss-120b> and",
        "<https://huggingface.co/openai/gpt-oss-20b>; file sizes from the `ggml-org` GGUF repositories.",
        "",
        "## The project owner's PC (i7-8700K, 48 GB DDR4-2133, GTX 750 2 GB, model on the 256 GB NVMe)",
        "",
        f"**Verdict for gpt-oss-120b: {r['verdict']}** — {r['speed_class']}, about {rng(r['tokens_per_s'])} tokens/s (estimate).",
        "",
        r["explanation"],
        "",
        "### Memory required (context 4096)",
        "",
        "| Item | GiB |",
        "|---|---|",
        f"| Weights | {v(rq['weights_gb'], 2)} |",
        f"| KV cache | {v(rq['kv_cache_gb'], 2)} |",
        f"| Compute buffers | {v(rq['compute_buffers_gb'], 2)} |",
        f"| Engine overhead | {v(rq['runtime_overhead_gb'], 2)} |",
        f"| Kept free for Windows and other apps | {v(rq['os_reserve_gb'], 2)} |",
        f"| Safety margin | {v(rq['safety_margin_gb'], 2)} |",
        f"| **Total** | **{v(rq['total_gb'], 2)}** |",
        "",
        "### What each amount of RAM would do",
        "",
        "| RAM | Outcome | Speed (estimate) | Paged from disk |",
        "|---|---|---|---|",
    ]
    for row in r["ram_table"]:
        speed = "not loadable" if not (row["tokens_per_s"] or {}).get("value") else f"{rng(row['tokens_per_s'])} t/s — {row['speed_class']}"
        lines.append(f"| {row['ram_gb']} GB{' ← this PC' if row['current'] else ''} | {row['outcome']} | {speed} | {v(row['spill_gb'], 1)} GiB |")
    g = r["gpu"]
    lines += ["", "### What the GTX 750 can and cannot do", "", g.get("benefit", ""), ""]
    lines += [f"* ✔ {t}" for t in g.get("can", [])] + [f"* ✘ {t}" for t in g.get("cannot", [])] + [f"* ℹ {t}" for t in g.get("notes", [])]
    rec = r["recommendation"]
    lines += ["", "### Recommendation", "", f"**{rec['title']}**", ""] + [f"1. {step}" for step in rec["steps"]]
    lines += ["", "## Other machines (same planner)", ""]
    lines += section("16 GB laptop, no GPU", "laptop-16gb")
    lines += section("32 GB desktop, RTX 3060 12 GB", "desktop-32gb-rtx3060")
    lines += section("128 GB workstation, RTX 4090", "workstation-128gb-rtx4090")
    lines += [
        "## What would turn the estimates into facts",
        "",
        "1. Install the app, open **Virtual GPU → GPT-OSS 120B** — the page checks your real RAM, free disk and the engine.",
        "2. Download the model from **Models → Hugging Face** (the app shows the 63.4 GB size and asks first; it never downloads on its own).",
        "3. Put the file on the NVMe drive, then run **Virtual GPU → Optimizer** with “Benchmark my current settings”. The result records load time, prompt-processing speed and generation speed separately, peak memory and page faults.",
        "4. If the benchmark and the estimate disagree, the Optimizer shows the difference; the assumptions behind each estimate are listed under the report.",
        "",
        "## Known gaps",
        "",
        "* The MoE byte split and compute-buffer sizes were calibrated against the 20B file size and small dense models, not against a real gpt-oss load log.",
        "* The speed range uses memory bandwidth and a drive-speed table, not a measurement of this PC. Paging estimates are conservative: they treat every spilled byte as equally hot, while real mixture-of-experts routing is skewed, so measured speed can land on either side.",
        "* The planner keeps 6 GB free for Windows and other apps by default (Settings → Virtual GPU → “Memory kept free”). On a 16 GB laptop that alone turns gpt-oss-20b from “fits” into “pages a little”; lower it if you close other apps.",
        "* CPU weight repacking (seen on AVX-512/AMX CPUs) can make resident memory up to ~2× the file size for some quantizations; the i7-8700K has neither, but the planner does not model it.",
        "* No GPU has been available for testing: GTX 750 behaviour (CUDA 12 PTX JIT on first start, R580 driver limit) is documented from NVIDIA/llama.cpp sources, not observed.",
        "",
    ]
    out = ROOT / "docs" / "GPT_OSS_120B.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
